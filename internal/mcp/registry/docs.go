package registry

import (
	"fmt"
	"strings"
)

// ToolsMarkdown renders the full tool reference `go run ./cmd/wsm-mcp tools`
// prints, and mcp/tools.md is a checked-in copy of this output —
// TestToolsMdIsCurrent fails if they ever drift.
func ToolsMarkdown(r *Registry, version string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# wsm-mcp tools\n\nGenerated by `go run ./cmd/wsm-mcp tools` (wsm-mcp %s, %d tools). Danger-gated tools refuse\n"+
		"unless WSM_MCP_ALLOW_DANGEROUS=true. Every result is `{\"host\": \"...\", ...}` naming which configured host answered.\n\n", version, len(r.List()))
	for _, t := range r.List() {
		fmt.Fprintf(&b, "## `%s`\n", t.Name)
		if t.Danger {
			fmt.Fprint(&b, "**DANGER** — refuses unless `WSM_MCP_ALLOW_DANGEROUS=true`.\n\n")
		}
		fmt.Fprintf(&b, "%s\n\n", t.Desc)
		if t.Route != "" {
			fmt.Fprintf(&b, "Wraps: `%s`\n\n", t.Route)
		}
		if t.WaxumMethod != "" {
			fmt.Fprintf(&b, "Wraps: `waxum.Client.%s`\n\n", t.WaxumMethod)
		}
		if len(t.Params) > 0 {
			for _, p := range t.Params {
				req, enum := "", ""
				if p.Required {
					req = " **required**"
				}
				if len(p.Enum) > 0 {
					enum = " (" + strings.Join(p.Enum, " \\| ") + ")"
				}
				fmt.Fprintf(&b, "- `%s` %s%s — %s%s\n", p.Name, p.Type, req, p.Desc, enum)
			}
			fmt.Fprintln(&b)
		}
	}
	return b.String()
}
